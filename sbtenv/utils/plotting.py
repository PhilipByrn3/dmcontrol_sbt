from datetime import datetime
from pathlib import Path


def save_figure(fig, script, folder='figures', dpi=300):
    """
    Stamp fig with the script that made it and the date and time, then save
    it as <folder>/<script name>_<YYYY-MM-DD_HH-MM-SS>.png. Pass __file__ as
    script. Returns the saved path.
    """
    now = datetime.now()
    name = Path(script).stem
    fig.text(0.99, 0.005, f'Generated by {Path(script).name} on {now:%Y-%m-%d %H:%M:%S}',
             ha='right', va='bottom', fontsize=7, color='0.45')
    out = Path(folder) / f'{name}_{now:%Y-%m-%d_%H-%M-%S}.png'
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=dpi)
    return out
